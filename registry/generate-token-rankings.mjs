function renderRuby(artifact, options = {}) {
  const value = model(artifact, options);
  return [
    "# frozen_string_literal: true",
    "",
    "# Generated by registry/generate-token-rankings.mjs. Do not edit.",
    "module ERPC",
    "  module TokenRankingsData",
    "    def self.deep_freeze(value)",
    "      value.each { |child| deep_freeze(child) } if value.is_a?(Array)",
    "      value.each_value { |child| deep_freeze(child) } if value.is_a?(Hash)",
    "      value.freeze",
    "    end",
    "    TOKEN_RANKINGS_METADATA = deep_freeze(" + ruby(value.metadata) + ")",
    "    TOKEN_RANKINGS = [",
    ...value.records.map((row) => "      " + ruby(row) + ".freeze,"),
    "    ].then { |rows| deep_freeze(rows) }",
    "    TOKEN_RANKINGS_CONTENT_DIGEST = TOKEN_RANKINGS_METADATA[:content_digest]",
    "  end",
    "end",
    "",
  ].join("\n");
}
export function renderLanguage(language, artifact = RANKINGS, options = {}) {
  if (!Object.hasOwn(OUTPUTS, language)) fail("unknown language: " + language);
  if (language === "typescript") return renderTypeScript(artifact, options);
  if (language === "rust") return renderRust(artifact, options);
  if (language === "python") return renderPython(artifact, options);
  if (language === "go") return renderGo(artifact, options);
  return renderRuby(artifact, options);
}
export const RENDERERS = Object.freeze(Object.fromEntries(LANGUAGES.map((language) => [language, (artifact = RANKINGS, options = {}) => renderLanguage(language, artifact, options)])));

function parseArguments(argumentsList) {
  const options = { language: null, check: false };
  for (let index = 0; index < argumentsList.length; index += 1) {
    const argument = argumentsList[index];
    if (argument === "--check") { options.check = true; continue; }
    if (argument === "--language") {
      if (options.language !== null || index + 1 >= argumentsList.length) fail("duplicate or missing --language");
      options.language = argumentsList[index + 1]; index += 1; continue;
    }
    if (argument.startsWith("--")) fail("unknown option " + argument);
    fail("unexpected argument " + argument);
  }
  if (options.language === null) fail("--language is required");
  if (options.language !== "all" && !LANGUAGES.includes(options.language)) fail("--language must be one of " + LANGUAGES.join(", ") + ", all");
  if (options.language === "all" && !options.check) fail("all is supported only with --check");
  if (options.check && options.language !== "all") fail("--check requires --language all");
  return options;
}
async function main() {
  const options = parseArguments(process.argv.slice(2));
  if (options.check) {
    for (const language of LANGUAGES) {
      const source = renderLanguage(language);
      const expectedPath = path.join(REPOSITORY_DIRECTORY, OUTPUTS[language]);
      const actual = await readFile(expectedPath, "utf8");
      if (actual !== source) fail(language + " generated ranking output is stale");
    }
    process.stdout.write("token ranking generated outputs are current\n");
    return;
  }
  const language = options.language;
  const expectedPath = path.join(REPOSITORY_DIRECTORY, OUTPUTS[language]);
  await writeFile(expectedPath, renderLanguage(language), "utf8");
}
if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  main().catch((error) => { process.stderr.write("generate-token-rankings: " + error.message + "\n"); process.exitCode = 1; });
}
