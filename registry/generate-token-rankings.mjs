#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import path from "node:path";

import { RANKINGS, validateRankingArtifact } from "./token-rankings.mjs";

const REGISTRY_DIRECTORY = path.dirname(fileURLToPath(import.meta.url));
const REPOSITORY_DIRECTORY = path.dirname(REGISTRY_DIRECTORY);

export const OUTPUTS = Object.freeze({
  typescript: "packages/typescript/src/generated/token_rankings.ts",
  rust: "packages/rust/src/generated/token_rankings.rs",
  python: "packages/python/src/erpc_sdk/_token_rankings_data.py",
  go: "packages/go/token_rankings_generated.go",
  ruby: "packages/ruby/lib/erpc_sdk/generated/token_rankings.rb",
});
export const LANGUAGES = Object.freeze(Object.keys(OUTPUTS));

function fail(message) { throw new Error(message); }
function json(value) { return JSON.stringify(value, null, 2); }
function q(value) { return JSON.stringify(value); }
function snake(value) { return value.replace(/[A-Z]/gu, (letter) => "_" + letter.toLowerCase()); }
function ruby(value) {
  if (value === null) return "nil";
  if (value === true) return "true";
  if (value === false) return "false";
  if (typeof value === "string") return "'" + value.replaceAll("\\", "\\\\").replaceAll("'", "\\'") + "'";
  if (Array.isArray(value)) return "[" + value.map(ruby).join(", ") + "]";
  if (typeof value === "object") return "{ " + Object.entries(value).map(([key, child]) => snake(key) + ": " + ruby(child)).join(", ") + " }";
  return String(value);
}
function python(value) {
  if (value === null) return "None";
  if (value === true) return "True";
  if (value === false) return "False";
  if (typeof value === "string") return q(value);
  if (Array.isArray(value)) return "[" + value.map(python).join(", ") + "]";
  if (typeof value === "object") return "{" + Object.entries(value).map(([key, child]) => q(snake(key)) + ": " + python(child)).join(", ") + "}";
  return String(value);
}
function rust(value) {
  return q(value).replaceAll("\\\\", "\\\\\\\\").replaceAll("\\\"", "\\\\\"");
}
function model(artifact, options = {}) {
  validateRankingArtifact(artifact, { tokenCatalog: options.tokenCatalog });
  return { metadata: artifact.metadata, records: artifact.records };
}
function formatSource(command, argumentsList, source) {
  const result = spawnSync(process.env[command === "rustfmt" ? "RUSTFMT" : "GOFMT"] ?? command, argumentsList, { input: source, encoding: "utf8" });
  return result.error || result.status !== 0 ? source : result.stdout;
}
function renderTypeScript(artifact, options = {}) {
  const value = model(artifact, options);
  const byChain = Object.fromEntries([...new Set(value.records.map((row) => row.chainId))].sort().map((chainId) => [chainId, value.records.filter((row) => row.chainId === chainId)]));
  return [
    "/* Generated by registry/generate-token-rankings.mjs. Do not edit. */",
    "",
    "export type TokenRankingMetric = 'onchain-total-supply-value-native' | 'global-circulating-market-cap-usd';",
    "export type TokenRankingStatus = 'unconfigured' | 'complete' | 'partial';",
    "export interface TokenRankingCoverage { readonly chainId: string; readonly totalDeployments: number; readonly rankedDeployments: number; readonly unrankedDeployments: number; readonly observedAt: string | null; }",
    "export interface TokenRankingMetadata { readonly schemaVersion: 1; readonly metric: TokenRankingMetric | null; readonly asOf: string | null; readonly contentDigest: string; readonly status: TokenRankingStatus; readonly coverage: readonly TokenRankingCoverage[]; readonly sourceIds: readonly string[]; }",
    "export interface TokenRanking { readonly rank: number; readonly chainId: string; readonly deploymentIds: readonly string[]; readonly metric: TokenRankingMetric; readonly valueNumerator: string; readonly valueDenominator: string; readonly quoteCurrency: 'native' | 'USD'; readonly quoteDeploymentId: string | null; readonly observedAt: string; readonly sourceId: string; readonly sourceAssetId: string | null; }",
    "const deepFreeze = <T>(value: T): Readonly<T> => { if (value && typeof value === 'object' && !Object.isFrozen(value)) { Object.freeze(value); for (const child of Object.values(value as Record<string, unknown>)) deepFreeze(child); } return value as Readonly<T>; };",
    "export const TOKEN_RANKINGS_METADATA = deepFreeze(" + json(value.metadata) + ") as TokenRankingMetadata;",
    "export const TOKEN_RANKINGS = deepFreeze(" + json(value.records) + ") as readonly TokenRanking[];",
    "export const TOKEN_RANKINGS_CONTENT_DIGEST = TOKEN_RANKINGS_METADATA.contentDigest;",
    "export const TOKEN_RANKINGS_BY_CHAIN = deepFreeze(" + json(byChain) + ") as Readonly<Record<string, readonly TokenRanking[]>>;",
    "",
  ].join("\n");
}
