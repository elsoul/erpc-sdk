function goString(value) {
  return JSON.stringify(String(value));
}

function goPointer(value) {
  return value === null ? "nil" : `dexString(${goString(value)})`;
}

function formatGoSource(source) {
  const lines = source.split("\n").map((line) => {
    const spaces = line.match(/^ */u)?.[0].length ?? 0;
    return spaces > 0 && spaces % 4 === 0 ? `${"\t".repeat(spaces / 4)}${line.slice(spaces)}` : line;
  });
  let index = 0;
  while (index < lines.length) {
    if (/^type [A-Za-z_][A-Za-z0-9_]* struct \{$/u.test(lines[index])) {
      const end = lines.indexOf("}", index + 1);
      if (end > index) {
        const fields = lines.slice(index + 1, end).map((line, offset) => {
          const match = line.match(/^(\t+)([A-Za-z_][A-Za-z0-9_]*)\s+(.+)$/u);
          return match ? { line: index + 1 + offset, indent: match[1], name: match[2], type: match[3] } : null;
        });
        if (fields.every(Boolean)) {
          const max = Math.max(...fields.map((field) => field.name.length));
          for (const field of fields) lines[field.line] = `${field.indent}${field.name}${" ".repeat(max - field.name.length + 1)}${field.type}`;
        }
      }
    }
    index += 1;
  }
  const mapStart = lines.findIndex((line) => line === "\treturn map[string]string{");
  if (mapStart !== -1) {
    const mapEnd = lines.findIndex((line, lineIndex) => lineIndex > mapStart && line === "\t}");
    const entries = lines.slice(mapStart + 1, mapEnd).map((line, offset) => {
      const match = line.match(/^(\t+)"([^"]+)":\s+(.+),$/u);
      return match ? { line: mapStart + 1 + offset, indent: match[1], key: match[2], value: match[3] } : null;
    });
    if (mapEnd > mapStart && entries.every(Boolean)) {
      const max = Math.max(...entries.map((entry) => entry.key.length));
      for (const entry of entries) lines[entry.line] = `${entry.indent}"${entry.key}":${" ".repeat(max - entry.key.length + 1)}${entry.value},`;
    }
  }
  return lines.join("\n");
}

