function q(value) {
  return JSON.stringify(String(value));
}

function jsonLiteral(value) {
  return JSON.stringify(value, null, 2);
}

function snake(value) {
  return value.replace(/[A-Z]/gu, (letter) => `_${letter.toLowerCase()}`);
}

function groupedAliases(model, field) {
  const groups = { ethereum: {}, solana: {}, avalancheC: {} };
  for (const alias of model.aliases) if (alias[field] !== null) groups[alias.namespace][alias.name] = alias[field];
  return groups;
}

function aliasGroupName(namespace, language) {
  return (language === "rust" || language === "python" || language === "ruby") && namespace === "avalancheC"
    ? "avalanche_c"
    : namespace;
}

function dexAliasReference(alias, language) {
  const group = aliasGroupName(alias.namespace, language);
  const root = alias.dexDeploymentId === null ? "pools" : "dexes";
  if (language === "typescript") return `${root}.${group}.${alias.name}`;
  if (language === "rust") return `${root}::${group}::${alias.name}`;
  if (language === "python") return `${root}.${group}.${alias.name}`;
  if (language === "go") {
    const prefix = alias.dexDeploymentId === null ? "Pool" : "Dex";
    return `${prefix}${group === "avalancheC" ? "AvalancheC" : group[0].toUpperCase() + group.slice(1)}${alias.name}`;
  }
  const constant = group === "avalanche_c" ? "AvalancheC" : group[0].toUpperCase() + group.slice(1);
  return `ERPC::${alias.dexDeploymentId === null ? "Pools" : "Dexes"}::${constant}[:${alias.name}]`;
}

// Output contract: provenance stays in the canonical source, while generated
// runtime records expose catalog metadata and immutable IDs. Alias rows point
// at the public dex/pool groups so each new alias has one target definition.
function pythonLiteral(value) {
  if (value === null) return "None";
  if (value === true) return "True";
  if (value === false) return "False";
  if (typeof value === "string") return q(value);
  if (Array.isArray(value)) return `[${value.map(pythonLiteral).join(", ")}]`;
  if (typeof value === "object") return `{${Object.entries(value).map(([key, child]) => `${q(snake(key))}: ${pythonLiteral(child)}`).join(", ")}}`;
  return String(value);
}

function rubyLiteral(value) {
  if (value === null) return "nil";
  if (value === true) return "true";
  if (value === false) return "false";
  if (typeof value === "string") return `'${value.replace(/\\/gu, "\\\\").replace(/'/gu, "\\'")}'`;
  if (Array.isArray(value)) return `[${value.map(rubyLiteral).join(", ")}]`;
  if (typeof value === "object") return `{ ${Object.entries(value).map(([key, child]) => `${snake(key)}: ${rubyLiteral(child)}`).join(", ")} }`;
  return String(value);
}

function rustString(value) {
  return `"${String(value).replace(/\\/gu, "\\\\").replace(/"/gu, "\\\"").replace(/\r/gu, "\\r").replace(/\n/gu, "\\n")}"`;
}

function rustOption(value) {
  return value === null ? "None" : `Some(${rustString(value)})`;
}

