function renderRuby(model) {
  const dexGroups = groupedAliases(model, "dexDeploymentId");
  const poolGroups = groupedAliases(model, "poolDefinitionId");
  const frozenRecord = (value) => `${rubyLiteral(value)}.freeze`;
  const frozenPool = (value) => `{ ${Object.entries(value).map(([key, child]) => key === "adapter"
    ? `adapter: ${rubyLiteral(child)}.freeze`
    : `${snake(key)}: ${rubyLiteral(child)}`).join(", ")} }.freeze`;
  const rubyAliasHash = (entries) => `{ ${Object.entries(entries).map(([name, id]) => `:${name} => ${rubyLiteral(id)}`).join(", ")} }.freeze`;
  const dexModules = ["ethereum", "solana", "avalancheC"].map((namespace) => {
    const constant = namespace === "avalancheC" ? "AvalancheC" : namespace[0].toUpperCase() + namespace.slice(1);
    return `    ${constant} = ${rubyAliasHash(dexGroups[namespace])}`;
  });
  const poolModules = ["ethereum", "solana", "avalancheC"].map((namespace) => {
    const constant = namespace === "avalancheC" ? "AvalancheC" : namespace[0].toUpperCase() + namespace.slice(1);
    return `    ${constant} = ${rubyAliasHash(poolGroups[namespace])}`;
  });
  const aliases = model.aliases.map((entry) => `{ namespace: ${rubyLiteral(entry.namespace)}, name: ${rubyLiteral(entry.name)}, dex_deployment_id: ${entry.dexDeploymentId === null ? "nil" : dexAliasReference(entry, "ruby")}, pool_definition_id: ${entry.poolDefinitionId === null ? "nil" : dexAliasReference(entry, "ruby")} }.freeze`).join(", ");
  return [
    "# frozen_string_literal: true",
    "",
    "# Generated by registry/generate-dex-catalog.mjs. Do not edit.",
    "",
    "module ERPC",
    "  module Dexes",
    ...dexModules,
    "  end",
    "",
    "  module Pools",
    ...poolModules,
    "  end",
    "",
    "  module DexCatalogData",
    `    DEX_CATALOG_VERSION = ${rubyLiteral(model.version)}`,
    `    DEX_CATALOG_AS_OF_DATE = ${rubyLiteral(model.asOfDate)}`,
    `    DEX_CATALOG_CONTENT_DIGEST = ${rubyLiteral(model.contentDigest)}`,
    `    DEX_CHAIN_IDS = ${rubyLiteral(model.chainIds)}.freeze`,
    `    DEX_DEPLOYMENTS = [${model.dexDeployments.map(frozenRecord).join(", ")}].freeze`,
    `    POOL_DEFINITIONS = [${model.poolDefinitions.map(frozenPool).join(", ")}].freeze`,
    `    NATIVE_WRAP_DEFINITIONS = [${model.nativeWrapDefinitions.map(frozenRecord).join(", ")}].freeze`,
    `    DEX_ALIASES = [${aliases}].freeze`,
    "  end",
    "end",
    "",
  ].join("\n");
}

export const RENDERERS = Object.freeze({
  typescript: renderTypeScript,
  rust: renderRust,
  python: renderPython,
  go: renderGo,
  ruby: renderRuby,
});

export function renderLanguage(language, catalog = CATALOG, options = {}) {
  if (!Object.hasOwn(RENDERERS, language)) fail(`unknown language ${language}; expected ${LANGUAGES.join(", ")}`);
  const referencedTokenCatalog = options?.tokenCatalog ?? (options?.deployments && options?.assets ? options : tokenCatalog);
  validateCatalog(catalog, { tokenCatalog: referencedTokenCatalog });
  return RENDERERS[language](dataModel(catalog, { tokenCatalog: referencedTokenCatalog }));
}

function outputPath(language) {
  const relativePath = OUTPUTS[language];
  if (typeof relativePath !== "string" || path.isAbsolute(relativePath)) fail(`output path for ${language} must be repository-relative`);
  const absolutePath = path.resolve(REPOSITORY_DIRECTORY, relativePath);
  const prefix = `${REPOSITORY_DIRECTORY}${path.sep}`;
  if (!absolutePath.startsWith(prefix)) fail(`output path for ${language} escapes the repository`);
  return absolutePath;
}

function usage() {
  return [
    "Usage:",
    "  node registry/generate-dex-catalog.mjs --language <typescript|rust|python|go|ruby>",
    "  node registry/generate-dex-catalog.mjs --check --language <all|typescript|rust|python|go|ruby>",
    "",
    "Options:",
    "  --language <language>  select exactly one generated data file, or all with --check",
    "  --check                compare generated bytes without writing",
    "  --previous <file>      validate immutable IDs and alias history against a snapshot",
    "  --help                 show this help",
  ].join("\n");
}

function parseArguments(argumentsList) {
  const options = { check: false, help: false, language: null, previous: null };
  for (let index = 0; index < argumentsList.length; index += 1) {
    const argument = argumentsList[index];
    if (argument === "--check") {
      if (options.check) fail("--check may be provided only once");
      options.check = true;
      continue;
    }
    if (argument === "--help") {
      if (options.help) fail("--help may be provided only once");
      options.help = true;
      continue;
    }
    if (argument === "--language") {
      if (options.language !== null) fail("--language may be provided only once");
      const language = argumentsList[index + 1];
      if (language === undefined || language.startsWith("--")) fail("--language requires a value");
      options.language = language;
      index += 1;
      continue;
    }
    if (argument === "--previous") {
      if (options.previous !== null) fail("--previous may be provided only once");
      const previous = argumentsList[index + 1];
      if (previous === undefined || previous.startsWith("--")) fail("--previous requires a file path");
      options.previous = previous;
      index += 1;
      continue;
    }
    if (argument.startsWith("--")) fail(`unknown option ${argument}`);
    fail(`unexpected argument ${argument}`);
  }
  if (options.help) {
    if (options.check || options.language !== null || options.previous !== null) fail("--help cannot be combined with other options");
    return options;
  }
  if (options.language === null) fail("--language is required");
  if (!options.check && options.language === "all") fail("--language all is supported only with --check; generation writes one language at a time");
  if (!options.check && !LANGUAGES.includes(options.language)) fail(`unknown language ${options.language}; expected ${LANGUAGES.join(", ")}`);
  if (options.check && options.language !== "all" && !LANGUAGES.includes(options.language)) fail(`unknown language ${options.language}; expected all or ${LANGUAGES.join(", ")}`);
  return options;
}

async function readPrevious(previousPath) {
  const absolutePath = path.resolve(process.cwd(), previousPath);
  let source;
  try { source = await readFile(absolutePath, "utf8"); } catch (error) { fail(`cannot read --previous ${previousPath}: ${error.message}`); }
  let previous;
  try { previous = JSON.parse(source); } catch (error) { fail(`cannot parse --previous ${previousPath} as JSON: ${error.message}`); }
  try { compareHistory(CATALOG, previous); } catch (error) { fail(`--previous ${previousPath} is not an immutable catalog history: ${error.message}`); }
}

async function ensureParentDirectoryExists(targetPath, language) {
  try {
    const parent = await stat(path.dirname(targetPath));
    if (!parent.isDirectory()) fail(`target parent for ${language} is not a directory`);
  } catch (error) {
    if (error?.code === "ENOENT") fail(`target parent for ${language} does not exist: ${path.dirname(targetPath)}`);
    throw error;
  }
}

async function checkLanguage(language) {
  const targetPath = outputPath(language);
  let actual;
  try { actual = await readFile(targetPath); } catch (error) {
    if (error?.code === "ENOENT") fail(`generated ${language} file is missing: ${path.relative(REPOSITORY_DIRECTORY, targetPath)}`);
    fail(`cannot read generated ${language} file: ${error.message}`);
  }
  const expected = Buffer.from(renderLanguage(language), "utf8");
  if (!actual.equals(expected)) fail(`generated ${language} file differs from the canonical renderer`);
  return `${language}: OK (${expected.length} bytes)`;
}

async function writeLanguage(language) {
  const targetPath = outputPath(language);
  await ensureParentDirectoryExists(targetPath, language);
  const expected = Buffer.from(renderLanguage(language), "utf8");
  let actual = null;
  try { actual = await readFile(targetPath); } catch (error) { if (error?.code !== "ENOENT") fail(`cannot read existing ${language} file: ${error.message}`); }
  if (actual?.equals(expected)) return `${language}: unchanged (${expected.length} bytes)`;
  try { await writeFile(targetPath, expected); } catch (error) { fail(`cannot write generated ${language} file: ${error.message}`); }
  return `${language}: wrote ${expected.length} bytes`;
}

export async function run(argumentsList = process.argv.slice(2)) {
  const options = parseArguments(argumentsList);
  if (options.help) { process.stdout.write(`${usage()}\n`); return; }
  validateCatalog(CATALOG);
  if (options.previous !== null) await readPrevious(options.previous);
  if (options.check) {
    const languages = options.language === "all" ? LANGUAGES : [options.language];
    const results = [];
    for (const language of languages) results.push(await checkLanguage(language));
    process.stdout.write(`${results.join("\n")}\n`);
    return;
  }
  process.stdout.write(`${await writeLanguage(options.language)}\n`);
}

const invokedPath = process.argv[1] === undefined ? null : pathToFileURL(path.resolve(process.argv[1])).href;
if (invokedPath !== null && import.meta.url === invokedPath) {
  run().catch((error) => {
    process.stderr.write(`generate-dex-catalog: ${error.message}\n`);
    process.exitCode = 1;
  });
}
