const RENDERERS = Object.freeze({ typescript: renderTypeScript, rust: renderRust, python: renderPython, ruby: renderRuby, go: renderGo });

/** Render one package's immutable data constants without touching the filesystem. */
export function renderLanguage(language, registry = canonicalRegistry) {
  if (!LANGUAGES.includes(language)) cliError(`unknown language ${language}; expected ${LANGUAGES.join(", ")}`);
  return RENDERERS[language](registry);
}

function parseArguments(argumentsList) {
  const options = { check: false, help: false, language: null, write: false };
  for (let index = 0; index < argumentsList.length; index += 1) {
    const argument = argumentsList[index];
    if (argument === "--check") {
      if (options.check || options.write) cliError("choose exactly one of --check or --write");
      options.check = true;
      continue;
    }
    if (argument === "--write") {
      if (options.check || options.write) cliError("choose exactly one of --check or --write");
      options.write = true;
      continue;
    }
    if (argument === "--help") {
      if (options.help) cliError("--help may be provided only once");
      options.help = true;
      continue;
    }
    if (argument === "--language") {
      if (options.language !== null) cliError("--language may be provided only once");
      const language = argumentsList[index + 1];
      if (language === undefined || language.startsWith("--")) cliError("--language requires a value");
      options.language = language;
      index += 1;
      continue;
    }
    if (argument.startsWith("--")) cliError(`unknown option ${argument}`);
    cliError(`unexpected argument ${argument}`);
  }
  if (options.help) {
    if (options.check || options.write || options.language !== null) cliError("--help cannot be combined with other options");
    return options;
  }
  if (!options.check && !options.write) cliError("one of --check or --write is required");
  if (options.language === null) cliError("--language is required");
  if (options.check && options.language !== "all" && !LANGUAGES.includes(options.language)) cliError(`unknown language ${options.language}; expected all or ${LANGUAGES.join(", ")}`);
  if (options.write && !LANGUAGES.includes(options.language)) cliError(`--write requires one language; expected ${LANGUAGES.join(", ")}`);
  return options;
}

function outputPath(language) {
  const relativePath = OUTPUTS[language];
  const absolutePath = path.resolve(REPOSITORY_DIRECTORY, relativePath);
  const repositoryPrefix = `${REPOSITORY_DIRECTORY}${path.sep}`;
  if (!absolutePath.startsWith(repositoryPrefix)) cliError(`model output path for ${language} escapes the repository`);
  return absolutePath;
}

async function ensureParentDirectoryExists(targetPath, language) {
  const parentPath = path.dirname(targetPath);
  try {
    const parent = await stat(parentPath);
    if (!parent.isDirectory()) cliError(`target parent for ${language} is not a directory: ${parentPath}`);
  } catch (error) {
    if (error?.code === "ENOENT") cliError(`target parent for ${language} does not exist: ${parentPath}; the language owner must create it within its package`);
    throw error;
  }
}

async function checkLanguage(language) {
  const targetPath = outputPath(language);
  let actual;
  try {
    actual = await readFile(targetPath, "utf8");
  } catch (error) {
    if (error?.code === "ENOENT") cliError(`generated ${language} file is missing: ${path.relative(REPOSITORY_DIRECTORY, targetPath)}`);
    throw error;
  }
  const expected = renderLanguage(language);
  if (actual !== expected) cliError(`generated ${language} file differs from the canonical renderer: ${path.relative(REPOSITORY_DIRECTORY, targetPath)}`);
  return `${language}: OK (${Buffer.byteLength(expected)} bytes)`;
}

async function writeLanguage(language) {
  const targetPath = outputPath(language);
  await ensureParentDirectoryExists(targetPath, language);
  const expected = renderLanguage(language);
  let actual = null;
  try { actual = await readFile(targetPath, "utf8"); } catch (error) { if (error?.code !== "ENOENT") throw error; }
  if (actual === expected) return `${language}: unchanged (${Buffer.byteLength(expected)} bytes)`;
  await writeFile(targetPath, expected);
  return `${language}: wrote ${Buffer.byteLength(expected)} bytes`;
}

function usage() {
  return [
    "Usage:",
    "  node registry/generate-swap-execution-capabilities.mjs --write --language <typescript|rust|python|go|ruby>",
    "  node registry/generate-swap-execution-capabilities.mjs --check --language <all|typescript|rust|python|go|ruby>",
    "",
    "The renderer is import-safe. --write updates exactly one package-owned file; --check is read-only.",
  ].join("\n");
}

export async function run(argumentsList = process.argv.slice(2)) {
  const options = parseArguments(argumentsList);
  if (options.help) {
    process.stdout.write(`${usage()}\n`);
    return;
  }
  validateSwapExecutionCapabilities(canonicalRegistry);
  if (options.check) {
    const languages = options.language === "all" ? LANGUAGES : [options.language];
    const results = [];
    for (const language of languages) results.push(await checkLanguage(language));
    process.stdout.write(`${results.join("\n")}\n`);
    return;
  }
  process.stdout.write(`${await writeLanguage(options.language)}\n`);
}

const invokedPath = process.argv[1] === undefined ? null : pathToFileURL(path.resolve(process.argv[1])).href;
if (invokedPath !== null && import.meta.url === invokedPath) {
  run().catch((error) => {
    process.stderr.write(`generate-swap-execution-capabilities: ${error.message}\n`);
    process.exitCode = 1;
  });
}
