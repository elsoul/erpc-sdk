#!/usr/bin/env node

import { readFile, stat, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

import canonicalRegistry from "./swap-execution-capabilities.json" with { type: "json" };
import {
  SWAP_EXECUTION_FUNCTION_SELECTOR,
  SWAP_EXECUTION_FUNCTION_SIGNATURE,
  computeDigest,
  runtimeProjection,
  validateSwapExecutionCapabilities,
} from "./swap-execution-capabilities.mjs";

const REGISTRY_DIRECTORY = path.dirname(fileURLToPath(import.meta.url));
const REPOSITORY_DIRECTORY = path.dirname(REGISTRY_DIRECTORY);

export const OUTPUTS = Object.freeze({
  typescript: "packages/typescript/src/generated/swap_execution_capabilities.ts",
  rust: "packages/rust/src/generated/swap_execution_capabilities.rs",
  python: "packages/python/src/erpc_sdk/_swap_execution_capabilities_data.py",
  go: "packages/go/swap_execution_capabilities_generated.go",
  ruby: "packages/ruby/lib/erpc_sdk/generated/swap_execution_capabilities.rb",
});
export const LANGUAGES = Object.freeze(["typescript", "rust", "python", "go", "ruby"]);

function cliError(message) {
  throw new Error(message);
}

function quote(value) {
  return JSON.stringify(String(value));
}

function chunks(value, size = 76) {
  const result = [];
  for (let index = 0; index < value.length; index += size) result.push(value.slice(index, index + size));
  return result;
}

function safeChunks(value, size = 76) {
  const result = [];
  let start = 0;
  while (start < value.length) {
    let end = Math.min(start + size, value.length);
    while (
      end < value.length &&
      end > start &&
      /[A-Za-z0-9._:-]/u.test(value[end - 1]) &&
      /[A-Za-z0-9._:-]/u.test(value[end])
    ) end -= 1;
    if (end === start) end = Math.min(start + size, value.length);
    result.push(value.slice(start, end));
    start = end;
  }
  return result;
}

function pythonStringExpression(value) {
  const parts = safeChunks(value).map((part) => `    ${quote(part)}`);
  return parts.length === 1 ? parts[0].trimStart() : `(\n${parts.join("\n")}\n)`;
}

function rubyString(value) {
  return `'${String(value).replace(/\\/gu, "\\\\").replace(/'/gu, "\\'")}'`;
}

function rustStringExpression(value) {
  const parts = safeChunks(value);
  const quoted = parts.map((part) => `${quote(part)}`);
  if (quoted.length === 1) return quoted[0];
  return `concat!(\n${quoted.map((part) => `    ${part},`).join("\n")}\n)`;
}

function pythonConstant(name, value) {
  return `${name} = (\n    ${quote(value)}\n)`;
}

function rustConst(name, value) {
  const literal = quote(value);
  const source = `pub(crate) const ${name}: &str = ${literal};`;
  return source.length > 100
    ? `pub(crate) const ${name}: &str =\n    ${literal};`
    : source;
}

function modelFor(registry = canonicalRegistry) {
  validateSwapExecutionCapabilities(registry);
  const rows = runtimeProjection(registry.capabilities);
  const json = JSON.stringify(rows);
  const asOfDate = registry.asOfDate;
  const digest = computeDigest(registry.capabilities);
  return { rows, json, asOfDate, digest };
}

export function renderTypeScript(registry = canonicalRegistry) {
  const model = modelFor(registry);
  return [
    "/* Generated by registry/generate-swap-execution-capabilities.mjs. Do not edit. */",
    "",
    `export const SWAP_EXECUTION_CAPABILITIES_JSON = ${quote(model.json)} as const;`,
    `export const SWAP_EXECUTION_CAPABILITIES_CONTENT_DIGEST = ${quote(model.digest)} as const;`,
    `export const SWAP_EXECUTION_CAPABILITIES_AS_OF_DATE = ${quote(model.asOfDate)} as const;`,
    `export const SWAP_EXECUTION_FUNCTION_SIGNATURE = ${quote(SWAP_EXECUTION_FUNCTION_SIGNATURE)} as const;`,
    `export const SWAP_EXECUTION_FUNCTION_SELECTOR = ${quote(SWAP_EXECUTION_FUNCTION_SELECTOR)} as const;`,
    "",
  ].join("\n");
}

