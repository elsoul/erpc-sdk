#!/usr/bin/env node

import { readFile, stat, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

import {
  CATALOG,
  OUTPUTS,
  compareHistory,
  computeDigest,
  renderLanguage,
  validateCatalog,
} from "./token-catalog.mjs";

const REGISTRY_DIRECTORY = path.dirname(fileURLToPath(import.meta.url));
const REPOSITORY_DIRECTORY = path.dirname(REGISTRY_DIRECTORY);
const LANGUAGES = Object.freeze(Object.keys(OUTPUTS));

function usage() {
  return [
    "Usage:",
    "  node registry/generate-token-catalog.mjs --language <typescript|rust|python|go|ruby>",
    "  node registry/generate-token-catalog.mjs --check --language <all|typescript|rust|python|go|ruby>",
    "",
    "Options:",
    "  --language <language>  select exactly one generated data file, or all with --check",
    "  --check                compare generated bytes without writing",
    "  --previous <file>      validate immutable IDs and alias history against a snapshot",
    "  --help                 show this help",
  ].join("\n");
}
function cliError(message) {
  throw new Error(message);
}

function parseArguments(argumentsList) {
  const options = { check: false, help: false, language: null, previous: null };
  for (let index = 0; index < argumentsList.length; index += 1) {
    const argument = argumentsList[index];
    if (argument === "--check") {
      if (options.check) cliError("--check may be provided only once");
      options.check = true;
      continue;
    }
    if (argument === "--help") {
      if (options.help) cliError("--help may be provided only once");
      options.help = true;
      continue;
    }
    if (argument === "--language") {
      if (options.language !== null) cliError("--language may be provided only once");
      const language = argumentsList[index + 1];
      if (language === undefined || language.startsWith("--")) cliError("--language requires a value");
      options.language = language;
      index += 1;
      continue;
    }
    if (argument === "--previous") {
      if (options.previous !== null) cliError("--previous may be provided only once");
      const previous = argumentsList[index + 1];
      if (previous === undefined || previous.startsWith("--")) cliError("--previous requires a file path");
      options.previous = previous;
      index += 1;
      continue;
    }
    if (argument.startsWith("--")) cliError(`unknown option ${argument}`);
    cliError(`unexpected argument ${argument}`);
  }

  if (options.help) {
    if (options.check || options.language !== null || options.previous !== null) {
      cliError("--help cannot be combined with other options");
    }
    return options;
  }
  if (options.language === null) cliError("--language is required");
  if (!options.check && options.language === "all") {
    cliError("--language all is supported only with --check; generation writes one language at a time");
  }
  if (options.check && options.language !== "all" && !LANGUAGES.includes(options.language)) {
    cliError(`unknown language ${options.language}; expected all or ${LANGUAGES.join(", ")}`);
  }
  if (!options.check && !LANGUAGES.includes(options.language)) {
    cliError(`unknown language ${options.language}; expected ${LANGUAGES.join(", ")}`);
  }
  return options;
}

function outputPath(language) {
  const relativePath = OUTPUTS[language];
  if (typeof relativePath !== "string" || path.isAbsolute(relativePath)) {
    cliError(`model output path for ${language} is not a repository-relative path`);
  }
  const absolutePath = path.resolve(REPOSITORY_DIRECTORY, relativePath);
  const repositoryPrefix = `${REPOSITORY_DIRECTORY}${path.sep}`;
  if (!absolutePath.startsWith(repositoryPrefix)) {
    cliError(`model output path for ${language} escapes the repository`);
  }
  return absolutePath;
}

async function readPrevious(previousPath) {
  const absolutePath = path.resolve(process.cwd(), previousPath);
  let source;
  try {
    source = await readFile(absolutePath, "utf8");
  } catch (error) {
    cliError(`cannot read --previous ${previousPath}: ${error.message}`);
  }
  let previous;
  try {
    previous = JSON.parse(source);
  } catch (error) {
    cliError(`cannot parse --previous ${previousPath} as JSON: ${error.message}`);
  }
  try {
    compareHistory(CATALOG, previous);
  } catch (error) {
    cliError(`--previous ${previousPath} is not an immutable catalog history: ${error.message}`);
  }
}

async function ensureParentDirectoryExists(targetPath, language) {
  const parentPath = path.dirname(targetPath);
  try {
    const parent = await stat(parentPath);
    if (!parent.isDirectory()) cliError(`target parent for ${language} is not a directory: ${parentPath}`);
  } catch (error) {
    if (error?.code === "ENOENT") {
      cliError(`target parent for ${language} does not exist: ${parentPath}; the language owner must create it within its package`);
    }
    if (error instanceof Error && error.message.startsWith("target parent")) throw error;
    cliError(`cannot inspect target parent for ${language}: ${error.message}`);
  }
}

async function checkLanguage(language) {
  const targetPath = outputPath(language);
  let actual;
  try {
    actual = await readFile(targetPath);
  } catch (error) {
    if (error?.code === "ENOENT") cliError(`generated ${language} file is missing: ${path.relative(REPOSITORY_DIRECTORY, targetPath)}`);
    cliError(`cannot read generated ${language} file: ${error.message}`);
  }
  const expected = Buffer.from(renderLanguage(language), "utf8");
  if (!actual.equals(expected)) {
    cliError(`generated ${language} file differs from the canonical renderer: ${path.relative(REPOSITORY_DIRECTORY, targetPath)}`);
  }
  return `${language}: OK (${expected.length} bytes)`;
}

async function writeLanguage(language) {
  const targetPath = outputPath(language);
  await ensureParentDirectoryExists(targetPath, language);
  const expected = Buffer.from(renderLanguage(language), "utf8");
  let actual = null;
  try {
    actual = await readFile(targetPath);
  } catch (error) {
    if (error?.code !== "ENOENT") cliError(`cannot read existing ${language} file: ${error.message}`);
  }
  if (actual?.equals(expected)) return `${language}: unchanged (${expected.length} bytes)`;
  try {
    await writeFile(targetPath, expected);
  } catch (error) {
    cliError(`cannot write generated ${language} file: ${error.message}`);
  }
  return `${language}: wrote ${expected.length} bytes`;
}

export async function run(argumentsList = process.argv.slice(2)) {
  const options = parseArguments(argumentsList);
  if (options.help) {
    process.stdout.write(`${usage()}\n`);
    return;
  }

  validateCatalog(CATALOG);
  const digest = computeDigest(CATALOG);
  if (digest !== CATALOG.contentDigest) cliError(`canonical catalog digest mismatch: expected ${digest}`);
  if (options.previous !== null) await readPrevious(options.previous);

  if (options.check) {
    const languages = options.language === "all" ? LANGUAGES : [options.language];
    const results = [];
    for (const language of languages) results.push(await checkLanguage(language));
    process.stdout.write(`${results.join("\n")}\n`);
    return;
  }
  process.stdout.write(`${await writeLanguage(options.language)}\n`);
}

const invokedPath = process.argv[1] === undefined ? null : pathToFileURL(path.resolve(process.argv[1])).href;
if (invokedPath !== null && import.meta.url === invokedPath) {
  run().catch((error) => {
    process.stderr.write(`generate-token-catalog: ${error.message}\n`);
    process.exitCode = 1;
  });
}
