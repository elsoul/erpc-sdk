#!/usr/bin/env node

import { readFile, stat, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

import canonicalRegistry from "./bridge-capabilities.json" with { type: "json" };
import {
  computeDigest,
  runtimeProjection,
  validateBridgeCapabilities,
} from "./bridge-capabilities.mjs";

const REGISTRY_DIRECTORY = path.dirname(fileURLToPath(import.meta.url));
const REPOSITORY_DIRECTORY = path.dirname(REGISTRY_DIRECTORY);

export const OUTPUTS = Object.freeze({
  typescript: "packages/typescript/src/generated/bridge_capabilities.ts",
  rust: "packages/rust/src/generated/bridge_capabilities.rs",
  python: "packages/python/src/erpc_sdk/_bridge_capabilities_data.py",
  go: "packages/go/bridge_capabilities_generated.go",
  ruby: "packages/ruby/lib/erpc_sdk/generated/bridge_capabilities.rb",
});
export const LANGUAGES = Object.freeze(["typescript", "rust", "python", "go", "ruby"]);

function cliError(message) {
  throw new Error(message);
}

function quote(value) {
  return JSON.stringify(String(value));
}

function chunks(value, size = 76) {
  const result = [];
  for (let index = 0; index < value.length; index += size) result.push(value.slice(index, index + size));
  return result;
}

function pythonStringExpression(value) {
  const parts = chunks(value).map((part) => `    ${quote(part)}`);
  return parts.length === 1 ? parts[0].trimStart() : `(\n${parts.join("\n")}\n)`;
}

function pythonConstant(name, value) {
  return `${name} = (\n    ${quote(value)}\n)`;
}

function rubyString(value) {
  return `'${String(value).replace(/\\/gu, "\\\\").replace(/'/gu, "\\'")}'`;
}

function rustStringExpression(value) {
  const parts = chunks(value).map((part) => `${quote(part)}`);
  if (parts.length === 1) return parts[0];
  return `concat!(\n${parts.map((part) => `    ${part},`).join("\n")}\n)`;
}

function rustConst(name, value) {
  const literal = quote(value);
  const source = `pub(crate) const ${name}: &str = ${literal};`;
  return source.length > 100 ? `pub(crate) const ${name}: &str =\n    ${literal};` : source;
}

function modelFor(registry = canonicalRegistry) {
  validateBridgeCapabilities(registry);
  const rows = runtimeProjection(registry.capabilities);
  const json = JSON.stringify(rows);
  const asOfDate = registry.asOfDate;
  const digest = computeDigest(registry.capabilities);
  return { rows, json, asOfDate, digest };
}

export function renderTypeScript(registry = canonicalRegistry) {
  const model = modelFor(registry);
  return [
    "/* Generated by registry/generate-bridge-capabilities.mjs. Do not edit. */",
    "",
    `export const BRIDGE_CAPABILITIES_JSON = ${quote(model.json)} as const;`,
    `export const BRIDGE_CAPABILITIES_CONTENT_DIGEST = ${quote(model.digest)} as const;`,
    `export const BRIDGE_CAPABILITIES_AS_OF_DATE = ${quote(model.asOfDate)} as const;`,
    "",
  ].join("\n");
}

export function renderRust(registry = canonicalRegistry) {
  const model = modelFor(registry);
  return [
    "// Generated by registry/generate-bridge-capabilities.mjs. Do not edit.",
    "",
    `pub(crate) const BRIDGE_CAPABILITIES_JSON: &str = ${rustStringExpression(model.json)};`,
    rustConst("BRIDGE_CAPABILITIES_CONTENT_DIGEST", model.digest),
    rustConst("BRIDGE_CAPABILITIES_AS_OF_DATE", model.asOfDate),
    "",
  ].join("\n");
}

export function renderPython(registry = canonicalRegistry) {
  const model = modelFor(registry);
  return [
    "# Generated by registry/generate-bridge-capabilities.mjs. Do not edit.",
    "",
    `BRIDGE_CAPABILITIES_JSON = ${pythonStringExpression(model.json)}`,
    pythonConstant("BRIDGE_CAPABILITIES_CONTENT_DIGEST", model.digest),
    `BRIDGE_CAPABILITIES_AS_OF_DATE = ${quote(model.asOfDate)}`,
    "",
  ].join("\n");
}

export function renderRuby(registry = canonicalRegistry) {
  const model = modelFor(registry);
  return [
    "# frozen_string_literal: true",
    "",
    "# Generated by registry/generate-bridge-capabilities.mjs. Do not edit.",
    "",
    "module ERPC",
    `  BRIDGE_CAPABILITIES_JSON = ${rubyString(model.json)}.freeze`,
    `  BRIDGE_CAPABILITIES_CONTENT_DIGEST = ${rubyString(model.digest)}.freeze`,
    `  BRIDGE_CAPABILITIES_AS_OF_DATE = ${rubyString(model.asOfDate)}.freeze`,
    "end",
    "",
  ].join("\n");
}

export function renderGo(registry = canonicalRegistry) {
  const model = modelFor(registry);
  return [
    "// Code generated by registry/generate-bridge-capabilities.mjs. DO NOT EDIT.",
    "",
    "package erpc",
    "",
    `const bridgeCapabilitiesJSON = ${quote(model.json)}`,
    `const bridgeCapabilitiesContentDigest = ${quote(model.digest)}`,
    `const bridgeCapabilitiesAsOfDate = ${quote(model.asOfDate)}`,
    "",
  ].join("\n");
}

const RENDERERS = Object.freeze({
  typescript: renderTypeScript,
  rust: renderRust,
  python: renderPython,
  go: renderGo,
  ruby: renderRuby,
});

/** Render one package's immutable bridge data without touching the filesystem. */
export function renderLanguage(language, registry = canonicalRegistry) {
  if (!LANGUAGES.includes(language)) cliError(`unknown language ${language}; expected ${LANGUAGES.join(", ")}`);
  return RENDERERS[language](registry);
}

function parseArguments(argumentsList) {
  const options = { check: false, help: false, language: null, write: false };
  for (let index = 0; index < argumentsList.length; index += 1) {
    const argument = argumentsList[index];
    if (argument === "--check") {
      if (options.check || options.write) cliError("choose exactly one of --check or --write");
      options.check = true;
      continue;
    }
    if (argument === "--write") {
      if (options.check || options.write) cliError("choose exactly one of --check or --write");
      options.write = true;
      continue;
    }
    if (argument === "--help") {
      if (options.help) cliError("--help may be provided only once");
      options.help = true;
      continue;
    }
    if (argument === "--language") {
      if (options.language !== null) cliError("--language may be provided only once");
      const language = argumentsList[index + 1];
      if (language === undefined || language.startsWith("--")) cliError("--language requires a value");
      options.language = language;
      index += 1;
      continue;
    }
    if (argument.startsWith("--")) cliError(`unknown option ${argument}`);
    cliError(`unexpected argument ${argument}`);
  }
  if (options.help) {
    if (options.check || options.write || options.language !== null) cliError("--help cannot be combined with other options");
    return options;
  }
  if (!options.check && !options.write) cliError("one of --check or --write is required");
  if (options.language === null) cliError("--language is required");
  if (options.check && options.language !== "all" && !LANGUAGES.includes(options.language)) cliError(`unknown language ${options.language}; expected all or ${LANGUAGES.join(", ")}`);
  if (options.write && !LANGUAGES.includes(options.language)) cliError(`--write requires one language; expected ${LANGUAGES.join(", ")}`);
  return options;
}

function outputPath(language) {
  const relativePath = OUTPUTS[language];
  const absolutePath = path.resolve(REPOSITORY_DIRECTORY, relativePath);
  const repositoryPrefix = `${REPOSITORY_DIRECTORY}${path.sep}`;
  if (!absolutePath.startsWith(repositoryPrefix)) cliError(`model output path for ${language} escapes the repository`);
  return absolutePath;
}

async function ensureParentDirectoryExists(targetPath, language) {
  const parentPath = path.dirname(targetPath);
  try {
    const parent = await stat(parentPath);
    if (!parent.isDirectory()) cliError(`target parent for ${language} is not a directory: ${parentPath}`);
  } catch (error) {
    if (error?.code === "ENOENT") cliError(`target parent for ${language} does not exist: ${parentPath}; the language owner must create it within its package`);
    throw error;
  }
}

async function checkLanguage(language) {
  const targetPath = outputPath(language);
  let actual;
  try {
    actual = await readFile(targetPath, "utf8");
  } catch (error) {
    if (error?.code === "ENOENT") cliError(`generated ${language} file is missing: ${path.relative(REPOSITORY_DIRECTORY, targetPath)}`);
    throw error;
  }
  const expected = renderLanguage(language);
  if (actual !== expected) cliError(`generated ${language} file differs from the canonical renderer: ${path.relative(REPOSITORY_DIRECTORY, targetPath)}`);
  return `${language}: OK (${Buffer.byteLength(expected)} bytes)`;
}

async function writeLanguage(language) {
  const targetPath = outputPath(language);
  await ensureParentDirectoryExists(targetPath, language);
  const expected = renderLanguage(language);
  let actual = null;
  try {
    actual = await readFile(targetPath, "utf8");
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  if (actual === expected) return `${language}: unchanged (${Buffer.byteLength(expected)} bytes)`;
  await writeFile(targetPath, expected);
  return `${language}: wrote ${Buffer.byteLength(expected)} bytes`;
}

function usage() {
  return [
    "Usage:",
    "  node registry/generate-bridge-capabilities.mjs --write --language <typescript|rust|python|go|ruby>",
    "  node registry/generate-bridge-capabilities.mjs --check --language <all|typescript|rust|python|go|ruby>",
    "",
    "The renderer is import-safe. --write updates exactly one package-owned file; --check is read-only.",
  ].join("\n");
}

export async function run(argumentsList = process.argv.slice(2)) {
  const options = parseArguments(argumentsList);
  if (options.help) {
    process.stdout.write(`${usage()}\n`);
    return;
  }
  validateBridgeCapabilities(canonicalRegistry);
  if (options.check) {
    const languages = options.language === "all" ? LANGUAGES : [options.language];
    const results = [];
    for (const language of languages) results.push(await checkLanguage(language));
    process.stdout.write(`${results.join("\n")}\n`);
    return;
  }
  process.stdout.write(`${await writeLanguage(options.language)}\n`);
}

const invokedPath = process.argv[1] === undefined ? null : pathToFileURL(path.resolve(process.argv[1])).href;
if (invokedPath !== null && import.meta.url === invokedPath) {
  run().catch((error) => {
    process.stderr.write(`generate-bridge-capabilities: ${error.message}\n`);
    process.exitCode = 1;
  });
}
